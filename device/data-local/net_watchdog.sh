#!/system/bin/sh
# Keeps the mirror reachable over Wi-Fi, and with it adb over Wi-Fi (port 5555). It never wakes the screen and never switches
# Wi-Fi off: a mirror whose screen is off has to stay dark, and Android turns Wireless debugging off at every Wi-Fi disconnect
# ("Network disconnected. Disabling adbwifi").
#
# Problems seen on the mirror (2026-11-07):
#  - While the screen is off Android puts the Wi-Fi chip into power saving: the driver's "suspend" mode (it drops broadcast
#    frames and wakes only every third DTIM) plus the radio's own power save. A packet from a machine that has no fresh
#    neighbour entry then waits 100-450 ms or gets lost, so `adb connect` and ping from the PC timed out for as long as the
#    screen slept, while Home Assistant's already open adb link kept working. Measured with the screen off, one ping every
#    300 ms: 116-299 ms with both on, 7-21 ms with both off.
#  - Once Wi-Fi is down, Android does not try to join again while the screen is off. The access point dropped the mirror at
#    01:20 (reason UNSPECIFIED, not generated by the mirror) and it was back only at 01:55. A test with the screen off
#    (Wi-Fi off and on) stayed offline for 15 minutes and rejoined 0.05 s after the screen was touched. Waking the screen
#    repairs it, but is not done here.
#  - adbd only listens on the TCP port while persist/service.adb.tcp.port is 5555; toggling USB debugging restarts adbd without it.
#
# What this does (one instance per boot, log /data/local/net_watchdog.log), every 20 s:
#  1) keeps the Wi-Fi chip awake: `wpa_cli driver SETSUSPENDMODE 0` when the driver says it is in suspend mode, and
#     `iwconfig wlan0 power off` when the radio power save is on. Android switches both back on at every screen-off, so this
#     is repeated; the mirror is on mains power.
#  2) pings the router. Three misses in a row (about a minute): `svc wifi enable` (a no-op if Wi-Fi is on), then
#     `wpa_cli reconnect` if the supplicant is DISCONNECTED, INACTIVE or SCANNING, then waits up to 40 s and logs the result.
#     At most 3 repairs per 30 minutes. (The reconnect step has not been tested against a real drop.)
#  3) checks that adbd listens on the port; if not for two checks, sets the properties again and restarts adbd.
#  4) every 5 minutes makes sure adb_enabled is 1 and puts Wireless debugging (adb_wifi_enabled) back on if Android left it off
#     while the router answers. The plain port 5555 does not depend on that setting.
PORT=5555
HEXPORT=15B3
WPA="/vendor/bin/wpa_cli -p /data/vendor/wifi/wpa/sockets -i wlan0"
LOG=/data/local/net_watchdog.log
PIDF=/data/local/tmp/net_watchdog.pid
# one instance only: the pid file survives a reboot, so its pid only counts if it is not our own and runs this script
oldpid=$(cat $PIDF 2>/dev/null)
if [ -n "$oldpid" ] && [ "$oldpid" != "$$" ] && grep -q net_watchdog /proc/$oldpid/cmdline 2>/dev/null; then exit 0; fi
echo $$ > $PIDF
log() {
  echo "$(date '+%m-%d %H:%M:%S') $*" >> $LOG
  if [ "$(wc -c < $LOG)" -gt 100000 ]; then tail -n 200 $LOG > $LOG.tmp && mv $LOG.tmp $LOG; fi
}
gateway() { ip route show table wlan0 2>/dev/null | awk '/^default/ {print $3; exit}'; }
wifi_ok() { gw=$(gateway); [ -n "$gw" ] && ping -c 1 -W 2 "$gw" > /dev/null 2>&1; }
adb_ok() { grep -Eiq ":$HEXPORT [0-9A-F:]+ 0A " /proc/net/tcp6 /proc/net/tcp 2>/dev/null; }

last_awake_log=0
keep_awake() {
  fixed=""
  if dmesg 2>/dev/null | grep dhd_set_suspend | tail -n 1 | grep -q 'force extra'; then
    $WPA driver SETSUSPENDMODE 0 > /dev/null 2>&1; fixed="driver suspend mode"
  fi
  if ! /vendor/bin/iwconfig wlan0 2>/dev/null | grep -q 'Power Management:off'; then
    /vendor/bin/iwconfig wlan0 power off > /dev/null 2>&1; fixed="$fixed radio power save"
  fi
  if [ -n "$fixed" ]; then
    now=$(date +%s)
    if [ $((now - last_awake_log)) -ge 60 ]; then last_awake_log=$now; log "Wi-Fi power saving was back on ($fixed), switched off again"; fi
  fi
}

router_wait() {   # $1 = seconds to wait for the router to answer
  t=0
  while [ $t -lt $1 ]; do wifi_ok && return 0; sleep 3; t=$((t + 3)); done
  return 1
}

wheals=0; wwin=$(date +%s)
wifi_heal() {
  now=$(date +%s)
  if [ $((now - wwin)) -gt 1800 ]; then wwin=$now; wheals=0; fi
  if [ $wheals -ge 3 ]; then log "skip: 3 Wi-Fi repairs in 30 minutes already"; return; fi
  wheals=$((wheals + 1))
  log "no answer from the router (repair $wheals; the screen is not touched)"
  svc wifi enable
  # Untested best effort: the supplicant keeps the saved network, so ask it to join again itself instead of waiting for
  # Android's scan (which does not run while the screen is off). Only when the supplicant is not connected, because a
  # reconnect on a working link would itself be a disconnect.
  st=$($WPA status 2>/dev/null | sed -n 's/^wpa_state=//p')
  case "$st" in
    DISCONNECTED|INACTIVE|SCANNING) $WPA reconnect > /dev/null 2>&1; log "supplicant state $st: asked it to reconnect" ;;
  esac
  if router_wait 40; then keep_awake; log "Wi-Fi is back"; else log "Wi-Fi is still down"; fi
}

log "watchdog started (pid $$)"
n=0
while [ "$(getprop sys.boot_completed)" != "1" ] && [ $n -lt 120 ]; do sleep 2; n=$((n + 1)); done
bad=0; adbbad=0; tick=0
while true; do
  if wifi_ok; then
    bad=0
  else
    bad=$((bad + 1))
    if [ $bad -ge 3 ]; then wifi_heal; bad=0; fi
  fi
  keep_awake
  if adb_ok; then
    adbbad=0
  else
    adbbad=$((adbbad + 1))
    if [ $adbbad -ge 2 ]; then
      log "adbd is not listening on port $PORT, restarting it"
      setprop persist.adb.tcp.port $PORT; setprop service.adb.tcp.port $PORT; setprop ctl.restart adbd
      adbbad=0; sleep 5
    fi
  fi
  tick=$((tick + 1))
  if [ $((tick % 15)) -eq 0 ]; then
    if [ "$(settings get global adb_enabled)" != "1" ]; then settings put global adb_enabled 1; log "adb_enabled was off, set to 1"; fi
    if [ "$(settings get global adb_wifi_enabled)" != "1" ] && wifi_ok; then
      settings put global adb_wifi_enabled 1; log "Wireless debugging was off, switched on again"
    fi
  fi
  sleep 20
done
